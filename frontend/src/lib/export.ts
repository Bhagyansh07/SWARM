import type { MissionDetailDto } from './types';

export interface ReportShape {
  summary: string;
  keyFindings: string[];
  risks: string[];
  verdict: string;
}

export interface AnalyticsShape {
  startedAt: string;
  completedAt: string;
  durationMs: number;
  totalTokens: number;
  estCostUsd: number;
  messages: number;
  graphNodes: number;
  graphEdges: number;
}

export interface ExportInput {
  id: string;
  name: string;
  template: string;
  status: string;
  provider: string;
  model: string;
  prompt: string;
  startedAt: string;
  completedAt: string | null;
  totalTokens: number;
  estCostUsd: number;
  report: ReportShape | null;
  analytics: AnalyticsShape | null;
}

export function toExportInput(detail: MissionDetailDto): ExportInput {
  return {
    id: detail.id,
    name: detail.name,
    template: detail.template,
    status: detail.status,
    provider: detail.provider,
    model: detail.model,
    prompt: detail.prompt,
    startedAt: detail.startedAt,
    completedAt: detail.completedAt,
    totalTokens: detail.totalTokens,
    estCostUsd: detail.estCostUsd,
    report: detail.report,
    analytics: detail.analytics,
  };
}

export function reportMarkdown(d: ExportInput): string {
  const lines: string[] = [
    `# SWARM Mission Report`,
    '',
    `> ${d.name} · ${d.template.replaceAll('_', ' ')} · ${d.status}`,
    '',
    `- **Mission ID:** \`${d.id}\``
  ];
  lines.push(`- **Model:** ${d.provider}/${d.model}`);
  lines.push(`- **Started:** ${new Date(d.startedAt).toISOString()}`);
  if (d.completedAt) lines.push(`- **Completed:** ${new Date(d.completedAt).toISOString()}`);
  lines.push('', '---', '');

  if (d.report) {
    const r = d.report;
    lines.push('## Verdict', '', r.verdict, '', '## Summary', '', r.summary, '');
    if (r.keyFindings.length) lines.push('## Key Findings', '', ...r.keyFindings.map((f) => `- ${f}`), '');
    if (r.risks.length) lines.push('## Risks', '', ...r.risks.map((r0) => `- ${r0}`), '');
  }

  lines.push('## Telemetry', '');
  lines.push(`- Tokens: **${d.analytics?.totalTokens ?? d.totalTokens}**`);
  if (d.analytics) {
    const a = d.analytics;
    const mins = Math.floor(a.durationMs / 60000);
    const secs = ((a.durationMs % 60000) / 1000).toFixed(1);
    lines.push(`- Duration: **${mins}m ${secs}s**`);
    lines.push(`- Estimated cost: **$${a.estCostUsd.toFixed(6)}**`);
    lines.push(`- Messages: **${a.messages}**`);
    lines.push(`- Graph: **${a.graphNodes} nodes / ${a.graphEdges} edges**`);
  }
  lines.push('', '---', '', `Generated by SWARM · ${new Date().toISOString()}`);
  return lines.join('\n');
}

export function reportJson(d: ExportInput): string {
  return JSON.stringify(
    {
      app: 'SWARM',
      kind: 'mission-report',
      version: 1,
      mission: {
        id: d.id,
        name: d.name,
        template: d.template,
        status: d.status,
        provider: d.provider,
        model: d.model,
        prompt: d.prompt,
        startedAt: d.startedAt,
        completedAt: d.completedAt,
        totalTokens: d.totalTokens,
        estCostUsd: d.estCostUsd,
      },
      report: d.report,
      analytics: d.analytics,
      exportedAt: new Date().toISOString(),
    },
    null,
    2,
  );
}

function download(filename: string, blob: Blob) {
  const url = URL.createObjectURL(blob);
  const anchor = document.createElement('a');
  anchor.href = url;
  anchor.download = filename;
  document.body.appendChild(anchor);
  anchor.click();
  anchor.remove();
  window.setTimeout(() => URL.revokeObjectURL(url), 4000);
}

export function downloadMarkdown(d: ExportInput, suffix?: string) {
  download(
    `swarm-${suffix ?? d.id}.md`,
    new Blob([reportMarkdown(d)], { type: 'text/markdown;charset=utf-8' }),
  );
}

export function downloadJson(d: ExportInput, suffix?: string) {
  download(
    `swarm-${suffix ?? d.id}.json`,
    new Blob([reportJson(d)], { type: 'application/json;charset=utf-8' }),
  );
}

/** Generic JSON download for non-report payloads (benchmarks, raw dumps). */
export function downloadJsValue(value: unknown, baseName: string) {
  download(
    `swarm-${baseName}.json`,
    new Blob([JSON.stringify(value, null, 2)], { type: 'application/json;charset=utf-8' }),
  );
}

export async function copyText(text: string): Promise<boolean> {
  try {
    await navigator.clipboard.writeText(text);
    return true;
  } catch {
    // Fallback for browsers without async clipboard (older iOS, http contexts)
    try {
      const ta = document.createElement('textarea');
      ta.value = text;
      ta.style.position = 'fixed';
      ta.style.opacity = '0';
      document.body.appendChild(ta);
      ta.select();
      document.execCommand('copy');
      ta.remove();
      return true;
    } catch {
      return false;
    }
  }
}